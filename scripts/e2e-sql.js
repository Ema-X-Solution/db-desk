// Runs the real app under Electron against a throwaway PostgreSQL and saves screenshots.
const { app, safeStorage } = require('electron');
safeStorage.isEncryptionAvailable = () => true; // no OS keyring in CI/headless
safeStorage.encryptString = (s) => Buffer.from(s);
safeStorage.decryptString = (b) => b.toString();
const EmbeddedPostgres = require('embedded-postgres').default;
const { BrowserWindow } = require('electron');
const fs = require('fs');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
app.setPath('userData', '/tmp/dbdesk-ud'); fs.rmSync('/tmp/dbdesk-ud', { recursive: true, force: true });
app.commandLine.appendSwitch('no-sandbox');
(async () => {
  const pg = new EmbeddedPostgres({ databaseDir: '/tmp/dbdesk-pg2', user: 'postgres', password: 'pw', port: 54330, persistent: false });
  fs.rmSync('/tmp/dbdesk-pg2', { recursive: true, force: true });
  await pg.initialise(); await pg.start(); await pg.createDatabase('sales');
  const { Client } = require('pg');
  const c = new Client({ host: '127.0.0.1', port: 54330, user: 'postgres', password: 'pw', database: 'sales' }); await c.connect();
  await c.query(`CREATE TABLE products(id serial primary key, name text not null, price numeric default 0, in_stock boolean default true)`);
  await c.query(`CREATE TABLE orders(id serial primary key, customer text, total numeric)`);
  await c.query(`INSERT INTO products(name, price) SELECT 'Item '||g, g*10 FROM generate_series(1,120) g`);
  await c.query(`INSERT INTO orders(customer,total) VALUES ('Sara',450),('Mona',120)`);
  await c.query('ANALYZE');
  require('../dist/main/main.js');
  await app.whenReady(); await sleep(1500);
  const win = BrowserWindow.getAllWindows()[0];
  win.webContents.on('console-message', (_e, _l, m) => console.log('[renderer]', m));
  if (win.webContents.isLoading()) await new Promise((r) => win.webContents.once('did-finish-load', r));
  const js = (s) => win.webContents.executeJavaScript(s).catch((e) => { console.log('JSFAIL', s.slice(0, 80), e.message); throw e; });
  const shot = async (n) => { await sleep(500); fs.writeFileSync(`/tmp/shots-sql/${n}.png`, (await win.webContents.capturePage()).toPNG()); };
  fs.mkdirSync('/tmp/shots-sql', { recursive: true });
  await js(`document.getElementById('newConn').click()`); await sleep(300);
  await js(`(()=>{const s=document.querySelector('#dialog select');s.value='mysql';s.dispatchEvent(new Event('change'))})()`);
  await shot('1b-mysql-type');
  await js(`(()=>{const s=document.querySelector('#dialog select');s.value='postgres';s.dispatchEvent(new Event('change'))})()`);
  await js(`(()=>{const v={Name:'Sales VPS',Host:'127.0.0.1',Port:'54330',Database:'sales',User:'postgres',Password:'pw'};
    document.querySelectorAll('#dialog label').forEach(l=>{const k=Object.keys(v).find(k=>l.firstChild.textContent.startsWith(k));const i=l.querySelector('input');if(k&&i)i.value=v[k];});})()`);
  await shot('1-new-connection');
  await js(`[...document.querySelectorAll('#dialog button')].find(b=>b.textContent.startsWith('Save')).click()`); await sleep(1500);
  await shot('2-connected');
  const setSql = (t) => js(`(()=>{const s=document.getElementById('sqlText');s.value=${JSON.stringify(t)};s.dispatchEvent(new Event('input'))})()`);
  const click = (id) => js(`document.getElementById('${id}').click()`);
  const st = () => js(`document.getElementById('sqlStatus').textContent`);
  const runDis = () => js(`document.getElementById('sqlRun').disabled`);
  const cnt = async () => (await c.query('SELECT count(*)::int n FROM products')).rows[0].n;
  await click('openSql'); await sleep(300);
  console.log('commit disabled at start:', await runDis());
  await shot('1-sql-empty');
  await setSql("BEGIN;\nDELETE FROM products WHERE id > 100;\nCOMMIT;"); await click('sqlDry'); await sleep(1000);
  console.log('BEGIN script ->', await st());
  await setSql("DELETE FROM products WHERE id > 100;\nSELECT count(*) AS remaining FROM products;\nSELECT id, name FROM products WHERE id > 98 ORDER BY id;");
  console.log('commit disabled before dry run:', await runDis());
  await click('sqlDry'); await sleep(1200);
  console.log('DRY ->', await st(), '| db rows:', await cnt(), '| commit disabled:', await runDis());
  await shot('2-dry-run');
  await setSql("DELETE FROM products WHERE id > 100;\nSELECT * FROM no_such_table;");
  await click('sqlDry'); await sleep(1000); await shot('3-error');
  console.log('ERR ->', await st(), '| db rows:', await cnt());
  await setSql("DELETE FROM products WHERE id > 100;\nSELECT count(*) AS remaining FROM products;"); await click('sqlDry'); await sleep(1000);
  console.log('commit enabled after dry run:', !(await runDis()));
  await js(`(()=>{const s=document.getElementById('sqlText');s.value+=' ';s.dispatchEvent(new Event('input'))})()`);
  console.log('commit disabled after edit:', await runDis());
  await click('sqlDry'); await sleep(1000);
  await click('sqlRun'); await sleep(400); await shot('4-commit-confirm');
  await js(`(()=>{const i=document.querySelector('#dialog input');i.value='COMMIT';i.dispatchEvent(new Event('input'))})()`);
  await js(`[...document.querySelectorAll('#dialog button')].find(b=>b.textContent==='Run and commit').click()`); await sleep(1500);
  console.log('COMMIT ->', await st(), '| db rows:', await cnt());
  await shot('5-committed');
  process.exit(0);
})();
