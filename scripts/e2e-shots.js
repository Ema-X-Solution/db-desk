// Runs the real app under Electron against a throwaway PostgreSQL and saves screenshots.
const { app, safeStorage } = require('electron');
safeStorage.isEncryptionAvailable = () => true; // no OS keyring in CI/headless
safeStorage.encryptString = (s) => Buffer.from(s);
safeStorage.decryptString = (b) => b.toString();
const EmbeddedPostgres = require('embedded-postgres').default;
const { BrowserWindow } = require('electron');
const fs = require('fs');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
app.setPath('userData', '/tmp/dbdesk-ud'); fs.rmSync('/tmp/dbdesk-ud', { recursive: true, force: true });
app.commandLine.appendSwitch('no-sandbox');
(async () => {
  const pg = new EmbeddedPostgres({ databaseDir: '/tmp/dbdesk-pg2', user: 'postgres', password: 'pw', port: 54330, persistent: false });
  fs.rmSync('/tmp/dbdesk-pg2', { recursive: true, force: true });
  await pg.initialise(); await pg.start(); await pg.createDatabase('sales');
  const { Client } = require('pg');
  const c = new Client({ host: '127.0.0.1', port: 54330, user: 'postgres', password: 'pw', database: 'sales' }); await c.connect();
  await c.query(`CREATE TABLE products(id serial primary key, name text not null, price numeric default 0, in_stock boolean default true)`);
  await c.query(`CREATE TABLE orders(id serial primary key, customer text, total numeric)`);
  await c.query(`INSERT INTO products(name, price) SELECT 'Item '||g, g*10 FROM generate_series(1,120) g`);
  await c.query(`INSERT INTO orders(customer,total) VALUES ('Sara',450),('Mona',120)`);
  await c.query('ANALYZE');
  require('../dist/main/main.js');
  await app.whenReady(); await sleep(1500);
  const win = BrowserWindow.getAllWindows()[0];
  win.webContents.on('console-message', (_e, _l, m) => console.log('[renderer]', m));
  if (win.webContents.isLoading()) await new Promise((r) => win.webContents.once('did-finish-load', r));
  const js = (s) => win.webContents.executeJavaScript(s).catch((e) => { console.log('JSFAIL', s.slice(0, 80), e.message); throw e; });
  const shot = async (n) => { await sleep(500); fs.writeFileSync(`/tmp/shots/${n}.png`, (await win.webContents.capturePage()).toPNG()); };
  fs.mkdirSync('/tmp/shots', { recursive: true });
  await js(`document.getElementById('newConn').click()`); await sleep(300);
  await js(`(()=>{const v={Name:'Sales VPS',Host:'127.0.0.1',Port:'54330',Database:'sales',User:'postgres',Password:'pw'};
    document.querySelectorAll('#dialog label').forEach(l=>{const k=Object.keys(v).find(k=>l.firstChild.textContent.startsWith(k));const i=l.querySelector('input');if(k&&i)i.value=v[k];});})()`);
  await shot('1-new-connection');
  await js(`[...document.querySelectorAll('#dialog button')].find(b=>b.textContent.startsWith('Save')).click()`); await sleep(1500);
  await shot('2-connected');
  await js(`[...document.querySelectorAll('#tableList .item')].find(i=>i.textContent.startsWith('products')).click()`); await sleep(800);
  await shot('3-table-data');
  await js(`[...document.querySelectorAll('#grid button')][0].click()`); await sleep(300);
  await shot('4-delete-confirm');
  await js(`[...document.querySelectorAll('#dialog button')].find(b=>b.textContent==='Delete row').click()`); await sleep(800);
  await shot('5-after-delete');
  await js(`document.getElementById('dropTable').click()`); await sleep(300);
  await js(`(()=>{const i=document.querySelector('#dialog input');i.value='products';i.dispatchEvent(new Event('input'))})()`);
  await shot('6-drop-confirm');
  await js(`[...document.querySelectorAll('#dialog button')].find(b=>b.textContent==='Drop table').click()`); await sleep(1000);
  await shot('7-after-drop');
  console.log('tables left:', await js(`document.getElementById('dbInfo').textContent`));
  app.exit(0);
})().catch((e) => { console.error(e); process.exit(1); });
